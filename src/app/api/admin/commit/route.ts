import { NextRequest, NextResponse } from "next/server";
import { products as currentProducts } from "@/lib/products";
import { z } from "zod";

const REPO_OWNER = "hairlabhyd";
const REPO_NAME = "hairlab-website";
const PRODUCTS_FILE = "src/lib/products.ts";

const CommitSchema = z.object({
  githubToken: z.string().min(20),
  passcode: z.string(),
  action: z.enum(["add", "update", "delete"]),
  product: z.object({
    id: z.string(),
    slug: z.string(),
    name: z.string(),
    subtitle: z.string(),
    description: z.string(),
    price: z.number().int().positive(),
    volume: z.string(),
    image: z.string(),
    tagline: z.string().nullable(),
    nights: z.number().int().nullable(),
    accentFrom: z.string(),
    accentTo: z.string(),
    ingredients: z.array(z.string()),
  }),
});

const ADMIN_PASSCODE = process.env.ADMIN_PASSCODE || "hairlab2026";

function generateProductsFile(products: any[]): string {
  const productStrings = products.map((p) => `  {
    id: "${p.id}",
    slug: "${p.slug}",
    name: "${p.name}",
    subtitle: "${p.subtitle}",
    description: "${p.description}",
    price: ${p.price},
    volume: "${p.volume}",
    image: "${p.image}",
    tagline: ${p.tagline === null ? "null" : `"${p.tagline}"`},
    nights: ${p.nights === null ? "null" : p.nights},
    accentFrom: "${p.accentFrom}",
    accentTo: "${p.accentTo}",
    ingredients: [${p.ingredients.map((i: string) => `"${i}"`).join(", ")}],
  }`);

  return `// Products stored as a simple JSON file - no database setup needed
// Edit this file directly to add/remove products
// This file is auto-generated by the admin panel - do not edit manually

export interface Product {
  id: string;
  slug: string;
  name: string;
  subtitle: string;
  description: string;
  price: number; // in paise (₹1 = 100 paise)
  volume: string;
  image: string;
  tagline: string | null;
  nights: number | null;
  accentFrom: string;
  accentTo: string;
  ingredients: string[];
}

export const products: Product[] = [
${productStrings.join(",\n")}
];

// Helper to find a product by ID (for cart operations)
export function findProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}
`;
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const parsed = CommitSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: "Invalid request", details: parsed.error.flatten() },
        { status: 400 }
      );
    }

    const { githubToken, passcode, action, product } = parsed.data;

    if (passcode !== ADMIN_PASSCODE) {
      return NextResponse.json({ error: "Invalid passcode" }, { status: 401 });
    }

    let newProducts: any[] = [];
    if (action === "add") {
      newProducts = [...currentProducts, product];
    } else if (action === "update") {
      newProducts = currentProducts.map((p) =>
        p.id === product.id ? product : p
      );
    } else if (action === "delete") {
      newProducts = currentProducts.filter((p) => p.id !== product.id);
    }

    const newFileContent = generateProductsFile(newProducts);

    const fileRes = await fetch(
      `https://api.github.com/repos/${REPO_OWNER}/${REPO_NAME}/contents/${PRODUCTS_FILE}`,
      {
        headers: {
          Authorization: `Bearer ${githubToken}`,
          Accept: "application/vnd.github.v3+json",
        },
      }
    );

    if (!fileRes.ok) {
      const err = await fileRes.json();
      return NextResponse.json(
        { error: `Could not fetch file: ${err.message}` },
        { status: 500 }
      );
    }

    const fileData = await fileRes.json();
    const sha = fileData.sha;

    const commitRes = await fetch(
      `https://api.github.com/repos/${REPO_OWNER}/${REPO_NAME}/contents/${PRODUCTS_FILE}`,
      {
        method: "PUT",
        headers: {
          Authorization: `Bearer ${githubToken}`,
          Accept: "application/vnd.github.v3+json",
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          message: `${action} product: ${product.name}`,
          content: Buffer.from(newFileContent).toString("base64"),
          sha,
        }),
      }
    );

    if (!commitRes.ok) {
      const err = await commitRes.json();
      return NextResponse.json(
        { error: `GitHub commit failed: ${err.message}` },
        { status: 500 }
      );
    }

    return NextResponse.json({
      success: true,
      message: `Product ${action}ed: ${product.name}. Vercel will redeploy in ~60 seconds.`,
    });
  } catch (e) {
    console.error("❌ /api/admin/commit error:", e);
    return NextResponse.json(
      { error: "Could not save product: " + (e as Error).message },
      { status: 500 }
    );
  }
}
